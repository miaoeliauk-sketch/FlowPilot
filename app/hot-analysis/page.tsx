function compactKeywords(parts: Array<string | undefined | null>): string[] {
  return Array.from(new Set(parts.flatMap(part => (part ?? "").split(/[、，,。\s#｜|/]+/)).map(s => s.trim()).filter(Boolean))).slice(0, 8);
}

