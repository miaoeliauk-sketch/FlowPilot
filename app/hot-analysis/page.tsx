function getViralCaseAdmission(result: AnalyzeResult | null) {
  if (!result?.evaluation) return { canCollect: false, reasons: ["尚未完成分析"] };
  const reasons: string[] = [];
  if (!result.hasRealMetrics) reasons.push("缺少真实互动数据");
  if (!result.evaluation.metricsLayerPassed) reasons.push(result.hasRealMetrics ? "点赞、评论、收藏、分享未达到爆款案例库阈值" : "尚未被验证为高表现内容");
  if (!result.evaluation.contentLayerPassed) reasons.push("内容层证据不足");
  if (!result.evaluation.structureLayerPassed) reasons.push("内容结构不完整");
  if (result.evaluation.exclusionMatched) reasons.push(`命中排除项：${result.evaluation.exclusionMatched}`);
  if (!result.evaluation.selfCheckPassed) reasons.push("自我检查未通过");
  const canCollect = result.hasRealMetrics
    && result.evaluation.metricsLayerPassed
    && result.evaluation.contentLayerPassed
    && result.evaluation.structureLayerPassed
    && !result.evaluation.exclusionMatched
    && result.evaluation.selfCheckPassed;
  return { canCollect, reasons: canCollect ? ["真实数据、内容结构和自我检查均通过，可作为历史表现样本。"] : reasons };
}

